#!/usr/bin/env node
// Deterministic fetch of the curated Twemoji SVG subset used by StickerFace.
// Dev-only: the repo ships the downloaded SVGs, so the app itself never needs
// network access. Re-run to repair or extend the set.
//
//   node scripts/fetch-emoji.mjs
//
// Artwork: Twemoji (CC-BY 4.0) — see assets/emoji/ATTRIBUTION.md, written here.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = process.env.TWEMOJI_VERSION ?? '15.1.0';
const BASE = `https://cdn.jsdelivr.net/gh/jdecked/twemoji@${VERSION}/assets/svg`;
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// [codepoint, human label] — faces first (the actual use case), then covers and animals.
const EMOJI = [
  ['1f600', 'grinning face'], ['1f603', 'grinning face big eyes'], ['1f604', 'grinning face smiling eyes'],
  ['1f601', 'beaming face'], ['1f606', 'grinning squinting face'], ['1f605', 'grinning face sweat'],
  ['1f923', 'rolling on the floor laughing'], ['1f602', 'face with tears of joy'], ['1f642', 'slightly smiling face'],
  ['1f643', 'upside-down face'], ['1f609', 'winking face'], ['1f60a', 'smiling face smiling eyes'],
  ['1f60d', 'smiling face heart eyes'], ['1f929', 'star-struck'], ['1f970', 'smiling face hearts'],
  ['1f60b', 'face savouring food'], ['1f61b', 'face with tongue'], ['1f61d', 'squinting face with tongue'],
  ['1f92a', 'zany face'], ['1f911', 'money-mouth face'], ['1f914', 'thinking face'],
  ['1f928', 'face with raised eyebrow'], ['1f610', 'neutral face'], ['1f611', 'expressionless face'],
  ['1f636', 'face without mouth'], ['1f60f', 'smirking face'], ['1f612', 'unamused face'],
  ['1f644', 'face with rolling eyes'], ['1f62c', 'grimacing face'], ['1f925', 'lying face'],
  ['1f60c', 'relieved face'], ['1f634', 'sleeping face'], ['1f637', 'face with medical mask'],
  ['1f912', 'face with thermometer'], ['1f915', 'face with head-bandage'], ['1f922', 'nauseated face'],
  ['1f92e', 'face vomiting'], ['1f927', 'sneezing face'], ['1f975', 'hot face'],
  ['1f976', 'cold face'], ['1f974', 'woozy face'], ['1f92f', 'exploding head'],
  ['1f971', 'yawnig face'], ['1f920', 'cowboy hat face'], ['1f973', 'partying face'],
  ['1f978', 'disguised face'], ['1f921', 'clown face'], ['1f479', 'ogre'],
  ['1f47a', 'goblin'], ['1f47b', 'ghost'], ['1f480', 'skull'], ['1f916', 'robot'],
  ['1f47d', 'alien'], ['1f63a', 'smiling cat'], ['1f63b', 'heart eyes cat'], ['1f638', 'grinning cat'],
  ['1f431', 'cat face'], ['1f436', 'dog face'], ['1f435', 'monkey face'], ['1f42d', 'mouse face'],
  ['1f439', 'hamster face'], ['1f430', 'rabbit face'], ['1f98a', 'fox face'], ['1f43c', 'panda'],
  ['1f428', 'koala'], ['1f42f', 'tiger face'], ['1f981', 'lion'], ['1f42e', 'cow face'],
  ['1f437', 'pig face'], ['1f438', 'frog face'], ['1f416', 'pig nose'],
  ['2b1b', 'black large square'], ['2b1c', 'white large square'],
  ['1f453', 'glasses'], ['1f576', 'sunglasses'], ['1f3ad', 'performing arts mask'],
];

const dir = join(ROOT, 'assets', 'emoji');
await mkdir(dir, { recursive: true });

const manifest = [];
const failed = [];
for (const [code, label] of EMOJI) {
  const file = `${code}.svg`;
  const res = await fetch(`${BASE}/${file}`);
  if (!res.ok) {
    failed.push(`${file} (HTTP ${res.status})`);
    continue;
  }
  const svg = await res.text();
  if (!svg.trimStart().startsWith('<svg')) {
    failed.push(`${file} (not SVG)`);
    continue;
  }
  await writeFile(join(dir, file), svg, 'utf8');
  manifest.push({ code, label, path: `assets/emoji/${file}` });
  process.stdout.write('.');
}

const generated = `// GENERATED by scripts/fetch-emoji.mjs — do not edit by hand.
// Twemoji ${VERSION}, CC-BY 4.0. See assets/emoji/ATTRIBUTION.md.
export const TWEMOJI_VERSION = ${JSON.stringify(VERSION)};

export const EMOJI = ${JSON.stringify(manifest, null, 2)};
`;
await writeFile(join(ROOT, 'js', 'emoji.js'), generated, 'utf8');

await writeFile(
  join(dir, 'ATTRIBUTION.md'),
  `# Emoji artwork attribution

The SVG files in this directory are unmodified copies of
[Twemoji](https://github.com/jdecked/twemoji) v${VERSION} graphics (CC-BY 4.0),
fetched by \`scripts/fetch-emoji.mjs\`.

- Copyright © X Corp. and contributors
- License: Creative Commons Attribution 4.0 International (CC-BY 4.0)
- Source: https://github.com/jdecked/twemoji

They are redistributed here under the terms of that license. The graphics are
used only to cover faces; the code in this repository is licensed separately
(MIT, see \`LICENSE\`).
`,
  'utf8',
);

console.log(`\n${manifest.length} SVG(s) written to assets/emoji/ (twemoji ${VERSION})`);
if (failed.length) {
  console.error(`FAILED (${failed.length}): ${failed.join(', ')}`);
  process.exitCode = 1;
}
